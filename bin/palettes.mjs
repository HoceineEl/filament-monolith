import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(process.argv[2] ?? join(root, 'node_modules/tailwindcss/theme.css'), 'utf8')

const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

const accents = ['blue', 'indigo', 'violet', 'rose', 'orange', 'amber', 'emerald', 'teal', 'sky']

const bases = {
    neutral: [0, 0],
    zinc: [286, 0.016],
    slate: [257, 0.046],
    gray: [264, 0.028],
    stone: [58, 0.013],
    mauve: [325, 0.022],
    olive: [110, 0.02],
    sage: [155, 0.018],
}

const grayLightness = [0.985, 0.967, 0.92, 0.871, 0.705, 0.552, 0.442, 0.37, 0.274, 0.21, 0.141]
const grayChroma = [0.15, 0.3, 0.45, 0.6, 0.9, 1, 1, 0.85, 0.65, 0.65, 0.6]

const parse = (name, shade) => {
    const match = source.match(new RegExp(`--color-${name}-${shade}:\\s*oklch\\(([\\d.]+)%\\s+([\\d.]+)\\s+([\\d.]+)\\)`))

    return [Number(match[1]) / 100, Number(match[2]), Number(match[3])]
}

const toLinearSrgb = ([l, c, h]) => {
    const a = c * Math.cos((h * Math.PI) / 180)
    const b = c * Math.sin((h * Math.PI) / 180)
    const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3

    return [
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
    ].map((v) => Math.min(1, Math.max(0, v)))
}

const luminance = (oklch) => {
    const [r, g, b] = toLinearSrgb(oklch)

    return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

const contrast = (x, y) => {
    const [a, b] = [luminance(x), luminance(y)].sort((p, q) => q - p)

    return (a + 0.05) / (b + 0.05)
}

const fmt = ([l, c, h]) => `oklch(${+l.toFixed(3)} ${+c.toFixed(3)} ${+h.toFixed(3)})`

const white = [1, 0, 0]

let css = `/* Generated by bin/palettes.mjs. Do not edit by hand. */\n\n`

css += `html.fi {\n`
shades.forEach((shade, i) => {
    css += `    --gray-${shade}: oklch(${grayLightness[i]} calc(var(--mn-c) * ${grayChroma[i]}) var(--mn-h));\n`
})
css += `}\n\n`

for (const [name, [hue, chroma]] of Object.entries(bases)) {
    css += `html.fi[data-mn-base='${name}'] {\n    --mn-h: ${hue};\n    --mn-c: ${chroma};\n}\n\n`
}

for (const name of accents) {
    const palette = Object.fromEntries(shades.map((shade) => [shade, parse(name, shade)]))
    const buttonShade = [600, 700, 800].find((shade) => contrast(palette[shade], white) >= 4.5)
    const darkButtonShade = [500, 600, 700].find((shade) => contrast(palette[shade], white) >= 4.5)

    css += `html.fi[data-mn-accent='${name}'] {\n`
    shades.forEach((shade) => {
        css += `    --primary-${shade}: ${fmt(palette[shade])};\n`
    })
    css += `    --mn-primary: var(--primary-${buttonShade});\n`
    css += `    --mn-primary-hover: var(--primary-${buttonShade + 100});\n`
    css += `    --mn-primary-fg: oklch(1 0 0);\n`
    css += `    --mn-ring: color-mix(in oklab, var(--primary-500) 55%, transparent);\n`
    css += `    --mn-accent-text: var(--primary-${buttonShade});\n`
    css += `}\n\n`

    css += `html.fi.dark[data-mn-accent='${name}'] {\n`
    css += `    --mn-primary: var(--primary-${darkButtonShade});\n`
    css += `    --mn-primary-hover: var(--primary-${darkButtonShade - 100});\n`
    css += `    --mn-accent-text: var(--primary-400);\n`
    css += `}\n\n`
}

writeFileSync(join(root, 'resources/css/palettes.css'), css)

console.log(`palettes.css written: ${accents.length} accents, ${Object.keys(bases).length} bases`)
